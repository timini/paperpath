// Writes src/content/catalog.ts: the small index the catalogue page needs, so full journeys
// (lessons, quizzes, widget parameters) can load only when opened. Run by `npm run build`.
import { readdirSync, writeFileSync } from "fs";
import { join } from "path";
import { JOURNEYS } from "../src/content/journeys";
import { previewNodeId } from "../src/content/graph";

const dir = join(import.meta.dirname, "../src/content/journeys");
const files = readdirSync(dir).filter((f) => f.endsWith(".ts") && f !== "index.ts");
const entries = [];
for (const j of JOURNEYS) {
  const file = await Promise.all(files.map(async (f) => [f, (await import(join(dir, f))).default?.id])).then((xs) => xs.find(([, id]) => id === j.id)?.[0]);
  if (!file) throw new Error(`no file exports journey ${j.id}`);
  entries.push({
    id: j.id,
    file: file.replace(/\.ts$/, ""),
    title: j.title,
    subtitle: j.subtitle,
    field: j.field,
    year: j.paper.year,
    authors: j.paper.authors.length > 2 ? `${j.paper.authors[0]} et al.` : j.paper.authors.join(" and "),
    accent: j.accent,
    nodeCount: j.nodes.length,
    minutes: j.nodes.reduce((s, n) => s + n.estimatedMinutes, 0),
    previewNodeId: previewNodeId(j),
  });
}
const out = `// Generated by scripts/build-catalog.ts. Do not edit by hand.
import type { CatalogEntry } from "./load";

export const CATALOG: CatalogEntry[] = ${JSON.stringify(entries, null, 2)};
`;
writeFileSync(join(import.meta.dirname, "../src/content/catalog.ts"), out);
console.log(`catalog: ${entries.length} journeys`);
